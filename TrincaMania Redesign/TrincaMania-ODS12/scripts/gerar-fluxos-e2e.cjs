/* global __dirname */
// Generates actual UI taps, never a shortcut that grants victory/rewards.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const ROOT = path.join(__dirname, '..');
require.extensions['.ts'] = (module, filename) =>
  module._compile(
    ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2020,
      },
      fileName: filename,
    }).outputText,
    filename,
  );
const boardService = require('../src/domain/recycling/services/BoardService.ts');
const { playTile } = require('../src/domain/recycling/services/PlayService.ts');
const {
  activeMatchRule,
} = require('../src/domain/recycling/policies/MatchRuleRegistry.ts');
const { createSeededRandom } = require('../src/utils/deterministicRandom.ts');
const { generatePlayableLevel } = require('../src/utils/levelGenerator.ts');
const { E2E_BOARD_SEED } = require('../src/testing/e2eProfile.ts');
const { criarJogador } = require('../tests/lib/solver.cjs');
const player = criarJogador({ ...boardService, playTile });
const check = process.argv.includes('--check');
const tutorial = require('../src/screens/game/practicalTutorial.ts');

for (let number = 1; number <= 5; number++) {
  const id = `w1-${String(number).padStart(3, '0')}`;
  const level = generatePlayableLevel(id, {
    random: createSeededRandom(E2E_BOARD_SEED),
  });
  const board = boardService.revealAvailableMysteryTiles(level.tiles);
  const result = player.simulateLevel(level, board, 7, activeMatchRule);
  if (!result.solved)
    throw new Error(`Unsolved fixture ${id}: ${result.reason}`);
  if (number === 1) {
    let tutorialBoard = board;
    let tutorialTray = [];
    const first = tutorial.findOpeningTutorialTile(board);
    for (let index = 0; index < 3; index++) {
      const expected = tutorial.getTutorialAvailableTiles(
        tutorialBoard,
        first.kind,
      )[0];
      if (result.path[index] !== expected.id)
        throw new Error('Solution must follow the real tutorial targets');
      const move = playTile(
        tutorialBoard,
        tutorialTray,
        expected.id,
        7,
        activeMatchRule,
      );
      tutorialBoard = move.board;
      tutorialTray = move.tray;
    }
  }
  const taps = result.path
    .map((id, index) => {
      let steps = `- tapOn:\n    id: 'board-tile-${id}'\n- waitForAnimationToEnd\n`;
      if (number === 1 && (index === 0 || index === 2)) {
        steps += `- tapOn:\n    id: tutorial-pratico-avancar\n- waitForAnimationToEnd\n`;
        if (index === 2)
          steps += `- tapOn:\n    id: tutorial-pratico-avancar\n- waitForAnimationToEnd\n`;
      }
      return steps;
    })
    .join('');
  const content =
    `# Generated by scripts/gerar-fluxos-e2e.cjs; seed ${E2E_BOARD_SEED}.\nappId: br.com.mhvtech.trincamania.e2e\n---\n` +
    taps +
    // These fixtures play levels 1..5 on a clean save. The fifth win grants
    // the first real campaign chest, above the victory modal.
    (number === 5
      ? "- assertVisible: 'Baú desbloqueado!'\n- tapOn: 'Coletar'\n"
      : '') +
    "- extendedWaitUntil:\n    visible: 'Vitória'\n    timeout: 15000\n";
  const filename = path.join(ROOT, '.maestro/subflows', `vencer-${id}.yaml`);
  if (check) {
    if (
      !fs.existsSync(filename) ||
      fs.readFileSync(filename, 'utf8') !== content
    )
      throw new Error(`Stale E2E flow ${filename}`);
  } else fs.writeFileSync(filename, content);
  console.log(`${id}: ${result.path.length} UI taps, verified solution`);
}

// A deliberate real loss, not a test-only life mutation.
const losingLevel = generatePlayableLevel('w1-002', {
  random: createSeededRandom(E2E_BOARD_SEED),
});
let budget = 10000;
function findLoss(board, tray, path = []) {
  if (--budget < 0) return undefined;
  const candidates = boardService
    .getPlayableTiles(board)
    .map((tile) => ({
      tile,
      move: playTile(board, tray, tile.id, 7, activeMatchRule),
    }))
    .sort((a, b) => b.move.tray.length - a.move.tray.length);
  for (const { tile, move } of candidates) {
    if (move.status === 'lost') return [...path, tile.id];
    if (move.status !== 'playing') continue;
    const found = findLoss(move.board, move.tray, [...path, tile.id]);
    if (found) return found;
  }
}
const losingPath = findLoss(
  boardService.revealAvailableMysteryTiles(losingLevel.tiles),
  [],
);
if (!losingPath) throw new Error('No deterministic losing path');
const lossContent =
  `# Generated by scripts/gerar-fluxos-e2e.cjs; seed ${E2E_BOARD_SEED}.\nappId: br.com.mhvtech.trincamania.e2e\n---\n` +
  losingPath
    .map(
      (id) =>
        `- tapOn:\n    id: 'board-tile-${id}'\n- waitForAnimationToEnd\n- tapOn:\n    text: 'Depois'\n    optional: true\n`,
    )
    .join('') +
  "- extendedWaitUntil:\n    visible: 'Bandeja cheia!'\n    timeout: 15000\n";
const lossFile = path.join(ROOT, '.maestro/subflows/perder-w1-002.yaml');
if (check) {
  if (fs.readFileSync(lossFile, 'utf8') !== lossContent)
    throw new Error('Stale losing flow');
} else fs.writeFileSync(lossFile, lossContent);
console.log(`w1-002: ${losingPath.length} UI taps, verified losing path`);
